using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Mvc;
using Paperless.Application.Abstractions;
using Paperless.Application.DTOs;

namespace Paperless.REST.Controllers;

/// <summary>Search recognized document content, titles and filenames through Elasticsearch.</summary>
[ApiController]
[Route("api/Documents/search")]
public class DocumentSearchController(IDocumentSearchService service) : ControllerBase
{
    /// <summary>Search current recognized originals with relevance ranking and optional spelling tolerance.</summary>
    /// <remarks>
    /// Searches OCR text, title and filename. All terms must match within a field; titles and filenames rank higher.
    /// Indexing is asynchronous. Results are validated against PostgreSQL so deleted or superseded originals are not returned.
    /// During synchronization isPartial can be true, totalCount null and a page shorter than pageSize.
    /// The first 10,000 indexed matches can be paged. Narrow the phrase for larger result sets.
    /// </remarks>
    /// <param name="q">A nonblank phrase of at most 200 characters without control characters.</param>
    /// <param name="fuzzy">Enable tolerance for small spelling differences.</param>
    /// <param name="page">One-based page; defaults to 1.</param>
    /// <param name="pageSize">Between 1 and 100 results; defaults to 20.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    [HttpGet]
    [ProducesResponseType(typeof(DocumentSearchDto), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ValidationProblemDetails), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status502BadGateway)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status503ServiceUnavailable)]
    public async Task<ActionResult<DocumentSearchDto>> Search([FromQuery, Required] string q,
        [FromQuery] bool fuzzy = false, [FromQuery] int page = 1, [FromQuery] int pageSize = 20, CancellationToken cancellationToken = default) =>
        Ok(await service.SearchAsync(q, fuzzy, page, pageSize, cancellationToken));

    /// <summary>Durably reschedule the complete search index from PostgreSQL without rerunning OCR.</summary>
    /// <remarks>
    /// Includes existing recognized originals and retained deletion markers. Does not wait for Elasticsearch or RabbitMQ.
    /// Repeated requests are safe but allocate new revisions and additional background work. Missing OCR is not generated by this call.
    /// </remarks>
    /// <param name="cancellationToken">Request cancellation token.</param>
    [HttpPost("reindex")]
    [ProducesResponseType(typeof(SearchReindexDto), StatusCodes.Status202Accepted)]
    public async Task<ActionResult<SearchReindexDto>> Reindex(CancellationToken cancellationToken) =>
        Accepted(await service.ReindexAsync(cancellationToken));
}
